const UPI_ID = 'singhayush8054@okaxis';
const PAYEE_NAME = 'Ayush Singh';

/**
 * Generates a UPI intent URL for deep linking
 * @param {number} amount - Amount in INR
 * @param {string} transactionNote - Note for the transaction
 * @returns {string} - UPI intent URL
 */
export const getUpiIntentUrl = (amount, transactionNote = 'Payment for buspay') => {
  const baseUrl = 'upi://pay';
  const params = new URLSearchParams({
    pa: UPI_ID,
    pn: PAYEE_NAME,
    tn: transactionNote,
    am: amount.toString(),
    cu: 'INR',
  });
  return `${baseUrl}?${params.toString()}`;
};

